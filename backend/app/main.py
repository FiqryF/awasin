"""ASGI application factory. Run from backend with python -m app."""

from contextlib import asynccontextmanager

import httpx
from fastapi import FastAPI
from starlette.middleware.cors import CORSMiddleware
from starlette.types import ASGIApp

from app.api.v1.router import router as api_router
from app.core.config import Settings
from app.core.exceptions import ErrorResponse, register_exception_handlers
from app.core.logging import configure_logging
from app.modules.health.router import APP_VERSION, router as health_router
from app.modules.identity.service import IdentityService
from app.modules.feedback.router import FeedbackLimiter
from app.modules.feedback.body_limit import FeedbackBodyLimit


def create_app(settings: Settings | None = None) -> ASGIApp:
    settings = settings if settings is not None else Settings()
    logger = configure_logging(settings.log_level)

    @asynccontextmanager
    async def lifespan(api: FastAPI):
        async with httpx.AsyncClient(timeout=5, follow_redirects=False, trust_env=False) as client:
            api.state.identity = IdentityService(settings, client)
            api.state.feedback_limiter = FeedbackLimiter()
            yield

    api = FastAPI(
        title=settings.app_name,
        version=APP_VERSION,
        description="AWASIN account, consent-based history and feedback API. Analysis engines are not implemented.",
        lifespan=lifespan,
        # Never let Starlette's traceback response bypass the safe error contract.
        debug=False,
        docs_url="/docs" if settings.docs_enabled else None,
        redoc_url="/redoc" if settings.docs_enabled else None,
        openapi_url="/openapi.json" if settings.docs_enabled else None,
        responses={422: {"model": ErrorResponse}, 500: {"model": ErrorResponse}},
    )
    api.state.settings = settings
    register_exception_handlers(api, logger)
    api.include_router(health_router)
    api.include_router(api_router, prefix=settings.api_v1_prefix)
    api.add_middleware(FeedbackBodyLimit, path=f'{settings.api_v1_prefix}/feedback')
    # Outer CORS also covers responses generated by the server-error handler.
    return CORSMiddleware(
        api,
        allow_origins=settings.cors_origins,
        allow_credentials=False,
        allow_methods=["GET", "PATCH", "POST", "DELETE"],
        allow_headers=["Accept", "Content-Type", "Authorization"],
    )
